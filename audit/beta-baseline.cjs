const fs = require('node:fs');
const path = require('node:path');
const { DatabaseSync } = require('node:sqlite');
const original = 'C:/Users/User/nmt-academy';
const reportDir = path.resolve('audit/reports');
fs.mkdirSync(reportDir, { recursive: true });
const env = require('dotenv').parse(fs.readFileSync(path.join(original, '.env')));
const url = process.env.NMT_WORKING_DATABASE_URL || env.DATABASE_URL;
if (!url?.startsWith('file:')) throw Error('SQLite DATABASE_URL expected');
let file = url.slice(5).split('?')[0];
if (!path.isAbsolute(file)) file = path.resolve(original, 'prisma', file);
if (!fs.existsSync(file)) throw Error('Working database not found: no connection created');
const snapshot = path.join(reportDir, '00-working-snapshot.db');
if (fs.existsSync(snapshot)) throw Error('Snapshot already exists; do not overwrite');
const source = new DatabaseSync(file, { readOnly: true });
source.exec(`VACUUM INTO '${snapshot.replaceAll("'", "''")}'`);
source.close();
const db = new DatabaseSync(snapshot, { readOnly: true });
const duplicateNicknames = db.prepare('SELECT lower(nickname) AS normalized, COUNT(*) AS count FROM User GROUP BY lower(nickname) HAVING COUNT(*) > 1').all();
const damagedTasks = db.prepare("SELECT id, userId, dateKey, status, templateKey, movedFromId, durationMin FROM StudyTask WHERE status='DROPPED' AND (templateKey LIKE 'moved-%' OR templateKey LIKE 'custom-%') ORDER BY dateKey, id").all();
const migrations = db.prepare('SELECT migration_name, finished_at, rolled_back_at FROM _prisma_migrations ORDER BY started_at').all();
const integrity = db.prepare('PRAGMA integrity_check').all();
const foreignKeys = db.prepare('PRAGMA foreign_key_check').all();
const report = { workingDatabasePath:file, snapshotPath:snapshot, sourceAccess:'readOnly; VACUUM INTO only', duplicateNicknames, damagedTasks, migrations, integrity, foreignKeys };
db.close();
fs.writeFileSync(path.join(reportDir, '00-db-snapshot.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify({snapshotPath:snapshot, duplicateNicknameGroups:duplicateNicknames.length, damagedTaskCount:damagedTasks.length, migrations:migrations.length, integrity, foreignKeyViolations:foreignKeys.length}, null, 2));
