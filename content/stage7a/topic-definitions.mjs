const LABELS = ["А", "Б", "В", "Г"];

function optionsFromTexts(texts) {
  return LABELS.map((label, i) => ({ label, text: texts[i] }));
}

function q(topicId, suffix, difficulty, prompt, correctAnswer, optionTexts, explanation, review) {
  const code = `s7a-${topicId}-${suffix}`;
  return {
    code,
    type: "SINGLE_CHOICE",
    difficulty,
    prompt,
    explanation,
    correctAnswer,
    options: optionsFromTexts(optionTexts),
    _review: review,
  };
}

function stripReview(question) {
  const { _review, ...rest } = question;
  return rest;
}

function reviewsFromQuestions(questions) {
  return questions.map((item) => ({
    questionId: item.code,
    reviewStatus: item._review.status,
    evidence: item._review.evidence,
    sources: item._review.sources,
  }));
}

function finalizeTopic(meta, lesson, questionItems) {
  const questions = questionItems.map(stripReview);
  return {
    ...meta,
    lesson,
    questions,
    reviewDecisions: reviewsFromQuestions(questionItems),
  };
}

