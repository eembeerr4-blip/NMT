  owner.on("pageerror", (error) => errors.push(`owner:${error.message}`));
  await owner.goto(`${base}/admin/invitations`);
  await expect(owner).toHaveURL(/\/login$/);
  await owner.getByLabel("Нікнейм або email").fill("owner");
  await owner.getByLabel("Пароль").fill(password);
