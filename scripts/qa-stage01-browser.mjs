import { chromium, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";

const base = process.env.QA_BASE_URL ?? "http://127.0.0.1:3101";
const password = process.env.QA_OWNER_PASSWORD;
if (!password) throw new Error("QA_OWNER_PASSWORD is required");
const output = "docs/stage01-qa";
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const errors = [];
const runId = Date.now().toString(36);
const studentEmail = `qa.stage01.${runId}@example.com`;
const linkedEmail = `qa.stage01.alt.${runId}@example.com`;
const studentNickname = `qa_${runId}`;
const studentPassword = "QA-student-password-123";

async function latestMail(prefix, recipient = studentEmail) {
  const messages = await (await fetch("http://127.0.0.1:3102/messages")).json();
  const match = [...messages].reverse().find((item) => item.to.includes(recipient) && item.text.includes(prefix));
  if (!match) throw new Error(`No QA mail containing ${prefix}`);
  const url = match.text.match(/http:\/\/127\.0\.0\.1:3101\/[^\s]+/)?.[0];
  if (!url) throw new Error("QA link missing");
  return url;
}

